# Gateway placement, read once from config/geometry.json via geometry_config
# (defaults to today's static_gw centroid placement if that file doesn't
# exist yet). K_RAIN/ALPHA_RAIN are computed dynamically from whatever
# elevation that placement resolves to (itur.models.itu838, not hardcoded
# per-scenario magic numbers), so any custom Gateway placement gets
# physically correct rain coefficients.
_GW_PLACEMENT = compute_placement('gateway')
# The UAV's own near-zenith feeder-hop geometry (static_gw: 0.1 km from the serving
# HAPS's nadir), for that hop's OWN rain exposure -- separate from, and much smaller
# than, the Gateway backhaul's -- see uav_feeder_rain_effect_on_capacity() below.
_UAV_PLACEMENT = compute_placement('uav')


class HAPSBatteryModel:
    """HAPS battery model with correct solar input from diurnal cycle."""

    def __init__(self, battery_capacity_wh=1000.0, panel_area_m2=20.0,
                 panel_efficiency=0.20):
        """Initialize HAPS battery parameters.

        Args:
            battery_capacity_wh: Total battery capacity (Wh)
            panel_area_m2: Solar panel area (m²)
            panel_efficiency: Panel efficiency (0.0-1.0)
        """
        self.battery_capacity = battery_capacity_wh  # Wh
        self.panel_area = panel_area_m2  # m²
        self.panel_efficiency = panel_efficiency  # 20% typical

    def solar_irradiance_diurnal(self, hour_of_day: float) -> float:
        """Compute solar irradiance based on DIURNAL cycle.

        CRITICAL: This depends on TIME-OF-DAY only, not weather.
        HAPS at 20 km is in stratosphere above clouds.

        Model: Cosine wave from sunrise (~6am) to sunset (~6pm)
        P_solar(t) = 600 · max(0, cos(π(t - 12) / 12)) W/m²

        Args:
            hour_of_day: Hour in range [0, 24)

        Returns:
            Solar irradiance in W/m²
        """
        # Nominal peak irradiance at equator, mid-altitude stratosphere
        peak_irradiance = 600.0  # W/m²

        # Sunrise at 6 AM, sunset at 6 PM (12-hour daylight)
        sunrise_hour = 6.0
        sunset_hour = 18.0

        if hour_of_day < sunrise_hour or hour_of_day > sunset_hour:
            return 0.0  # Night

        # Cosine wave centered at noon (12:00)
        # At t=12, cos(0)=1 → peak; at t=6 or t=18, cos(±π)=-0.5 → low
        phase = np.pi * (hour_of_day - 12.0) / 12.0
        irradiance = peak_irradiance * np.maximum(0.0, np.cos(phase))

        return irradiance

    def solar_power_generated(self, hour_of_day: float) -> float:
        """Compute solar power generated by HAPS panels.

        P_solar = Irradiance × Panel Area × Efficiency

        Args:
            hour_of_day: Hour in range [0, 24)

        Returns:
            Solar power in Watts
        """
        irradiance = self.solar_irradiance_diurnal(hour_of_day)
        power = irradiance * self.panel_area * self.panel_efficiency
        return power

    def update_battery_soc(self, current_soc_percent: float, hour_of_day: float,
                          user_load_watts: float,
                          feeder_link_power_base: float = 500.0,
                          platform_power: float = 200.0) -> Tuple[float, dict]:
        """Update HAPS battery state of charge for one hour.

        Energy balance: ΔE = P_solar - (P_feeder + P_platform + P_user)

        Args:
            current_soc_percent: Current battery SoC (0-100%)
            hour_of_day: Hour in range [0, 24)
            user_load_watts: Assigned user load (Watts)
            feeder_link_power_base: Baseline feeder link power (Watts)
            platform_power: Platform payload + guidance power (Watts)

        Returns:
            Tuple of (new_soc_percent, debug_dict)
        """
        # Input power: DIURNAL SOLAR ONLY (not weather-dependent)
        p_solar = self.solar_power_generated(hour_of_day)

        # Output power: Fixed + user load
        # NOTE: Feeder link rain affects LINK CAPACITY (SINR), not power consumption
        p_load = feeder_link_power_base + platform_power + user_load_watts

        # Net power (Watts)
        p_net = p_solar - p_load

        # Energy change over 1 hour (Wh)
        energy_change_wh = p_net * 1.0  # 1 hour

        # New SoC (energy_change_wh / capacity is a fraction of capacity;
        # scale to percentage points before adding to a percent value)
        new_soc_percent = current_soc_percent + 100.0 * (energy_change_wh / self.battery_capacity)
        new_soc_percent = np.clip(new_soc_percent, 0.0, 100.0)

        debug = {
            "hour_of_day": hour_of_day,
            "solar_irradiance_w_m2": self.solar_irradiance_diurnal(hour_of_day),
            "p_solar_w": p_solar,
            "p_feeder_w": feeder_link_power_base,
            "p_platform_w": platform_power,
            "p_user_w": user_load_watts,
            "p_load_total_w": p_load,
            "p_net_w": p_net,
            "energy_change_wh": energy_change_wh,
            "soc_before": current_soc_percent,
            "soc_after": new_soc_percent
        }

        return new_soc_percent, debug


def _rain_loss_db(rain_mm_h: float, placement: dict, h_rain_km: float = 5.278) -> dict:
    """ITU-R P.838 specific attenuation + P.618 slant-path reduction, for whichever
    hop's placement dict is passed in (Gateway backhaul or UAV feeder -- same formula,
    different elevation/altitude/rain coefficients, since both derive from
    geometry_config.compute_placement()). h_rain_km: ITU-R P.839 rain height for Delhi
    (28.61 N, 77.21 E) -- site-specific, not geometry-specific."""
    K_RAIN, ALPHA_RAIN = placement['k_rain'], placement['alpha_rain']
    H_NEAR_END_KM = placement['alt_m'] / 1000.0
    ELEVATION_DEG = placement['elevation_deg']

    specific_db_per_km = K_RAIN * (max(rain_mm_h, 0.0) ** ALPHA_RAIN)

    # ITU-R P.618 slant path through the rain layer.
    slant_rain_km = (h_rain_km - H_NEAR_END_KM) / np.sin(np.radians(ELEVATION_DEG))
    horiz_rain_km = slant_rain_km * np.cos(np.radians(ELEVATION_DEG))

    # P.618 path reduction factor (Eq. 2.2.1.1 of ITU-R P.618).
    reduction_factor = 1.0 / (1.0 + 0.78 * np.sqrt(horiz_rain_km * specific_db_per_km)
                              - 0.38 * (1.0 - np.exp(-2.0 * horiz_rain_km)))

    effective_path_km = slant_rain_km * reduction_factor
    total_rain_loss_db = specific_db_per_km * effective_path_km

    return {
        "rain_mm_h": rain_mm_h,
        "rain_attenuation_db_per_km": specific_db_per_km,
        "effective_path_km": effective_path_km,
        "total_rain_loss_db": total_rain_loss_db
    }


def feeder_link_rain_effect_on_capacity(rain_mm_h: float) -> dict:
    """Backhaul (HAPS-to-Gateway) rain attenuation (affects CAPACITY, not battery).

    NOTE: This is SEPARATE from battery model.
    Rain affects link SINR/capacity, not platform power consumption.

    Gateway placement comes from config/geometry.json (see models/geometry_config.py;
    defaults to today's static_gw centroid placement, ~37.53 km horizontal offset from
    the serving HAPS, circumradius of the 65 km equilateral triangle -- not co-located
    under the HAPS). The feeder-hop elevation angle (and therefore the ITU-R P.838
    specific-attenuation coefficients, which depend on elevation via the
    horizontal/vertical polarisation mix, P.618 Sec. 2.2.1.1) is derived from that
    placement, not hardcoded: gamma_R = K_RAIN * R^ALPHA_RAIN [dB/km].

    Args:
        rain_mm_h: Rainfall rate (mm/h)

    Returns:
        Dict with attenuation and resulting capacity
    """
    return _rain_loss_db(rain_mm_h, _GW_PLACEMENT)


def uav_feeder_rain_effect_on_capacity(rain_mm_h: float) -> dict:
    """UAV relay's OWN feeder-hop (HAPS-to-UAV, near-zenith) rain attenuation --
    separate from, and (at Delhi's R_0.1=15.7 mm/h) larger than,
    feeder_link_rain_effect_on_capacity()'s backhaul figure above (~16.6 dB vs.
    ~8.6 dB), because this hop's near-90-deg elevation (static_gw: UAV 0.1 km
    from the serving HAPS's own nadir) stays inside the rain cell for its whole
    traversal instead of crossing it obliquely, which the ITU-R P.618 reduction
    factor derates less than the backhaul's shallower, longer slant path.
    Previously this hop's capacity (channel_model.py) only modelled free-space
    loss + scintillation, with no rain term at all, which made the relay and
    direct paths' rain exposure identical in the DQN's reward by omission, not
    by any genuine physical equivalence -- this function is what closes that
    gap."""
    return _rain_loss_db(rain_mm_h, _UAV_PLACEMENT)


# ===== Unit Tests =====

def test_solar_at_midnight():
    """Test: Solar power is zero at midnight"""
    battery = HAPSBatteryModel()
    solar_power = battery.solar_power_generated(hour_of_day=0.0)  # Midnight
    assert solar_power == 0.0, f"Expected 0 W at midnight, got {solar_power} W"
    print("[PASS] test_solar_at_midnight")


def test_solar_at_noon():
    """Test: Solar power peaks at noon"""
    battery = HAPSBatteryModel()
    solar_power = battery.solar_power_generated(hour_of_day=12.0)  # Noon

    # Should be peak: 600 W/m² × 20 m² × 0.2 = 2400 W
    expected = 600.0 * 20.0 * 0.20
    assert np.isclose(solar_power, expected), f"Expected {expected} W, got {solar_power} W"
    print("[PASS] test_solar_at_noon")


def test_battery_drain_at_night():
    """Test: Battery drains at night (no solar input)"""
    battery = HAPSBatteryModel()

    # At midnight with user load: should lose energy
    soc_before = 100.0
    soc_after, debug = battery.update_battery_soc(
        current_soc_percent=soc_before,
        hour_of_day=0.0,  # Midnight (no solar)
        user_load_watts=100.0
    )

    assert soc_after < soc_before, "Battery should drain at night"
    assert debug['p_solar_w'] == 0.0, "Solar power should be zero at night"
    print(f"[PASS] test_battery_drain_at_night (SoC: {soc_before}% -> {soc_after:.1f}%)")


def test_battery_stable_at_noon_with_load():
    """Test: Battery approximately stable at noon if load < solar"""
    battery = HAPSBatteryModel()

    # At noon with moderate load: solar should mostly offset load
    soc_before = 50.0
    user_load = 100.0  # 100 W user load

    soc_after, debug = battery.update_battery_soc(
        current_soc_percent=soc_before,
        hour_of_day=12.0,  # Noon (peak solar)
        user_load_watts=user_load
    )

    # At noon: P_solar ≈ 2400 W
    # P_load = 500 + 200 + 100 = 800 W
    # P_net ≈ 1600 W → battery charges
    assert soc_after > soc_before, "Battery should charge at noon with positive P_net"
    print(f"[PASS] test_battery_stable_at_noon_with_load (SoC: {soc_before}% -> {soc_after:.1f}%)")


